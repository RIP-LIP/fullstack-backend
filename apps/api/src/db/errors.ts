/**
 * 数据层自己的错误类型。
 *
 * ## 为什么它不住在驱动文件里
 *
 * 换库之前它住在 `db/sqlite.ts` 里，而它和 SQLite 没有任何关系——
 * 它说的是「你把事务边界画错了」，换哪个数据库这句话都成立。
 * 跟着驱动一起搬家，它就该待在驱动外面。
 *
 * 这个文件就是「换库这件事逼出来的一个改动」的第一个例子：
 * 东西没挪之前，你以为它属于 SQLite。
 */

/**
 * 不支持嵌套事务。
 *
 * 原来没有这个类型，报错是从数据库直接漏出来的
 * （cannot start a transaction within a transaction）。两个问题：
 * 一是那句话对读代码的人没有意义，二是它经过错误处理之后会变成 500，
 * 而「你把事务边界画错了」是一个应该在开发期就看清的错误，
 * 不该伪装成「服务端出错了」。
 */
export class NestedTransactionError extends Error {
  constructor() {
    super(
      [
        '不支持嵌套事务。',
        '',
        '这说明边界画错了：内层想开的事务应该和外层是同一个，',
        '或者它们本来就该是两个互不相干的事务，不该一个套一个。',
        '加个计数器把嵌套「支持」起来只会让问题更晚暴露。',
      ].join('\n'),
    )
    this.name = 'NestedTransactionError'
  }
}
